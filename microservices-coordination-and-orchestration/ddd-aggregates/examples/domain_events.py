"""Demonstrate an aggregate-generated Domain Event, not Event Sourcing.

The event is an in-memory notification, not a database event store or a broker
message. The aggregate persists its CURRENT STATE through a repository.
"""
from dataclasses import asdict
from app.domain.models import Order, OrderLineItem


def create_order_and_event(consumer_id, restaurant_id):
    order = Order.create(consumer_id, restaurant_id,
                         [OrderLineItem("PIZZA", "Pizza", 10.0, 1)])
    events = order.collect_domain_events()
    assert len(events) == 1
    return order, events[0]


if __name__ == "__main__":
    order, event = create_order_and_event("CUST_1", "REST_1")
    print("Current aggregate state:", order)
    print("Domain event generated by the aggregate:", asdict(event))
    print("Collecting events again:", order.collect_domain_events())
    print("These events are NOT persisted or replayed to rebuild the Order.")
    print("Real reliable delivery requires an outbox in the same DB transaction.")

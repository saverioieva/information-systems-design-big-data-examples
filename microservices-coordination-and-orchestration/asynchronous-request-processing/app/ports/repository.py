"""Outbound order repository port, independent of SQLite."""
from typing import Protocol

class OrderRepository(Protocol):
    def initialize(self) -> None: ...
    def create(self, order_id: str, consumer_id: str, item: str) -> None: ...
    def get(self, order_id: str) -> dict | None: ...
    def record_validation(self, order_id: str, source: str, ok: bool) -> dict | None: ...

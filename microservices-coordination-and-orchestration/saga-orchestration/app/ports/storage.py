"""Outbound transaction port. An implementation owns its own local DB."""
from typing import Protocol, ContextManager
class SagaTransaction(Protocol):
    def seen(self,message_id:str) -> bool: ...
    def mark_seen(self,message_id:str) -> None: ...
    def enqueue(self,route:str,order_id:str,**payload) -> None: ...
    def create_order(self,order_id:str,customer_id:str,amount:float) -> None: ...
    def get_order(self,order_id:str) -> dict | None: ...
    def get_stage(self,order_id:str) -> str | None: ...
    def set_stage(self,order_id:str,stage:str) -> None: ...
    def amount(self,order_id:str) -> float: ...
    def create_ticket(self,order_id:str) -> None: ...
    def update_ticket(self,order_id:str,state:str) -> None: ...
    def authorize_card(self,order_id:str,status:str) -> None: ...

class SagaStore(Protocol):
    def initialize(self) -> None: ...
    def transaction(self) -> ContextManager[SagaTransaction]: ...
    def pending(self) -> dict | None: ...
    def mark_sent(self,event_id:str) -> None: ...

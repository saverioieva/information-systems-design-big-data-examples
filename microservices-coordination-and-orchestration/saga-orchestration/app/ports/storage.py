"""Ports for transactional persistence and asynchronous outbox dispatch."""
from typing import Protocol, ContextManager


class SagaTransaction(Protocol):
    def seen(self, message_id: str) -> bool: ...
    def mark_seen(self, message_id: str) -> None: ...
    def enqueue(self, route: str, order_id: str, **payload) -> None: ...
    def create_order(self, order_id: str, customer_id: str, amount: float,
                     retry_demo: bool = False, ticket_failure: bool = False) -> None: ...
    def get_order(self, order_id: str) -> dict | None: ...
    def get_stage(self, order_id: str) -> str | None: ...
    def set_stage(self, order_id: str, stage: str) -> None: ...
    def apply_order_status(self, order_id: str, status: str) -> None: ...
    def amount(self, order_id: str) -> float: ...
    def retry_demo(self, order_id: str) -> bool: ...
    def ticket_failure(self, order_id: str) -> bool: ...
    def create_ticket(self, order_id: str) -> None: ...
    def update_ticket(self, order_id: str, state: str) -> None: ...
    def authorize_card(self, order_id: str, status: str) -> None: ...
    def completed_command(self, order_id: str, action: str) -> str | None: ...
    def record_completed_command(self, order_id: str, action: str, result: str) -> None: ...
    def record_attempt(self, order_id: str, action: str, attempt: int, outcome: str) -> None: ...
    def record_transition(self, order_id: str, prior: str | None, event: str,
                          stage: str, command: str | None) -> None: ...
    def get_history(self, order_id: str) -> list[dict]: ...


class SagaStore(Protocol):
    def initialize(self) -> None: ...
    def transaction(self) -> ContextManager[SagaTransaction]: ...
    def pending(self) -> dict | None: ...
    def mark_sent(self, event_id: str) -> None: ...

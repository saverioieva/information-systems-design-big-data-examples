"""Outbound database port: ONE transaction writes state + outbox."""
from typing import Protocol
from app.domain.order import OrderCreated

class OutboxRepository(Protocol):
    def initialize(self) -> None: ...
    def save_order_and_message(self, event: OrderCreated) -> None: ...
    def find_order(self, order_id: str) -> dict | None: ...
    def pending(self) -> dict | None: ...
    def mark_sent(self, event_id: str) -> None: ...
    def outbox_rows(self) -> list[dict]: ...
    def received_rows(self) -> list[dict]: ...
    def record_delivery(self, event_id: str, order_id: str) -> None: ...

from typing import Protocol
from app.domain.order import OrderCreated

class OrderRepository(Protocol):
    def save_and_enqueue(self, order: OrderCreated) -> None: ...
    def find_order(self, order_id: str) -> dict | None: ...
    def outbox_rows(self) -> list[dict]: ...
    def received_rows(self) -> list[dict]: ...
    def record_received(self,event_id:str,order_id:str) -> None: ...

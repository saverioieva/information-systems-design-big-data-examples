"""Order storage port: atomic writes to business and publication-intent tables."""
from typing import Protocol


class OrderStore(Protocol):
    def create(self, order_id: str, amount: float, event: dict) -> None: ...
    def approve(self, order_id: str, event_factory): ...
    def list_orders(self) -> list[dict]: ...
    def list_outbox(self) -> list[dict]: ...

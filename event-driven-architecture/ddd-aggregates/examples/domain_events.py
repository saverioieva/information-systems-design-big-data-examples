"""Demonstrate how an Aggregate emits an in-memory Domain Event.

This standalone script has no database or broker. The HTTP use cases in the
same lab persist publication intents in integration_outbox via a Unit of Work.
"""
from dataclasses import asdict
from app.domain.models import Order, OrderLineItem


def create_order_and_event(consumer_id, restaurant_id):
    order = Order.create(consumer_id, restaurant_id,
                         [OrderLineItem("PIZZA", "Pizza", 10.0, 1)])
    events = order.collect_domain_events()
    assert len(events) == 1
    return order, events[0]


if __name__ == "__main__":
    order, event = create_order_and_event("CUST_1", "REST_1")
    print("Current aggregate state:", order)
    print("Domain event generated by the aggregate:", asdict(event))
    print("Collecting events again:", order.collect_domain_events())
    print("This standalone script collects facts in memory; the HTTP lab uses integration_outbox.")
    print("The Order API commits current state and selected integration intents in one transaction.")

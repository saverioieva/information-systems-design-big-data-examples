"""Application-facing port for event-sourced order commands and queries.

The outbound eventsourcing adapter implements this contract.  This is not a
repository of SQL rows: it manages a stream of domain events and snapshots.
"""
from typing import Protocol
from uuid import UUID
from typing import Any

class OrderStore(Protocol):
    def create_order(self, consumer_id: str, restaurant_id: str, items: list[dict]) -> UUID: ...
    def add_item_to_order(self, order_id: UUID, menu_item_id: str, name: str, price: float, quantity: int, expected_version: int | None = None) -> None: ...
    def approve_order(self, order_id: UUID, expected_version: int | None = None) -> None: ...
    def cancel_order(self, order_id: UUID, expected_version: int | None = None) -> None: ...
    def get_order(self, order_id: UUID) -> Any: ...
    def get_order_version(self, order_id: UUID, version: int) -> Any: ...
